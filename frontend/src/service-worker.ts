import { precacheAndRoute, cleanupOutdatedCaches } from 'workbox-precaching';
import { clientsClaim } from 'workbox-core';
import { registerRoute } from 'workbox-routing';
import { StaleWhileRevalidate, CacheFirst } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import { db } from './lib/db.js';

const swSelf = self as any;

swSelf.skipWaiting();
clientsClaim();
cleanupOutdatedCaches();

swSelf.addEventListener("message", (event: any) => {
  if (event.data && event.data.type === "SKIP_WAITING") swSelf.skipWaiting();
});

// Precache all assets generated by Vite
// Workbox will replace self.__WB_MANIFEST with the precache manifest array.
precacheAndRoute(self.__WB_MANIFEST || []);

// --- PWABuilder Required Logic Events ---

/**
 * 1. Fetch Event (Bulletproof Offline Support)
 * PWABuilder looks for a fetch listener that handles navigation requests.
 */
swSelf.addEventListener('fetch', (event: any) => {
  const url = new URL(event.request.url);

  // OS share sheet (share_target): stash the payload in IndexedDB and
  // hand off to the /share route — the backend never sees this request.
  if (event.request.method === 'POST' && url.pathname === '/share-target') {
    event.respondWith(
      (async () => {
        try {
          const form = await event.request.formData();
          const str = (k: string) => {
            const v = form.get(k);
            return typeof v === 'string' && v.length > 0 ? v : undefined;
          };
          const files = form
            .getAll('files')
            .filter((v: unknown) => v instanceof File && (v as File).size > 0) as File[];
          await db.shareStash.put({
            id: 'share',
            title: str('title'),
            text: str('text'),
            url: str('url'),
            files: files.length > 0 ? files : undefined,
            ts: Date.now(),
          });
        } catch (e) {
          console.warn('[Service Worker] share stash failed:', e);
        }
        return Response.redirect('/share', 303);
      })()
    );
    return;
  }

  if (event.request.mode === 'navigate') {
    event.respondWith(
      fetch(event.request).catch(() => {
        return caches.match('/index.html') as Promise<Response>;
      })
    );
  }
});

/**
 * 2. Push Notifications
 * Full support for incoming background notifications.
 */
swSelf.addEventListener('push', (event: any) => {
  let data: any = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch (e) {
    data = { title: 'Blink', body: event.data ? event.data.text() : 'New message', senderId: 'unknown' };
  }
  
  const title = data.title || 'Blink';
  const senderId = data.senderId || 'unknown';
  const tag = `blink-msg-${senderId}`; // Batching by senderId
  
  const options = {
    body: data.body || 'New message in Blink',
    icon: '/icon-512.png',
    badge: '/icon-192.png',
    tag: tag,
    renotify: true,
    data: {
      url: data.url || '/',
    },
    actions: [
      { action: 'open', title: 'Open' },
      { action: 'close', title: 'Dismiss' }
    ]
  };

  event.waitUntil(swSelf.registration.showNotification(title, options));
});

